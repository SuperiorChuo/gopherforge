CREATE TABLE IF NOT EXISTS hermes_entitlements (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  user_id bigint NOT NULL,
  enabled boolean NOT NULL DEFAULT false,
  policy_id bigint NOT NULL DEFAULT 0,
  device_limit integer NOT NULL DEFAULT 1,
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_entitlement_device_limit CHECK (device_limit BETWEEN 1 AND 10)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_entitlements_tenant_user
  ON hermes_entitlements (tenant_id, user_id);
CREATE INDEX IF NOT EXISTS idx_hermes_entitlements_tenant_enabled
  ON hermes_entitlements (tenant_id, enabled);

-- 注册申请尚未绑定登录用户，因此本表刻意不使用标准 tenant_id 字段，避免被
-- GORM 租户插件当成已认证业务记录。批准后再写 approved_tenant_id/user_id。
CREATE TABLE IF NOT EXISTS hermes_device_codes (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  device_code_hash char(64) NOT NULL,
  user_code_hash char(64) NOT NULL,
  public_key varchar(128) NOT NULL,
  key_fingerprint char(64) NOT NULL,
  device_name varchar(80) NOT NULL DEFAULT '',
  platform varchar(16) NOT NULL,
  arch varchar(16) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'pending',
  approved_tenant_id bigint DEFAULT NULL,
  approved_user_id bigint DEFAULT NULL,
  approved_at timestamptz(3) DEFAULT NULL,
  consumed_at timestamptz(3) DEFAULT NULL,
  expires_at timestamptz(3) NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_device_code_status
    CHECK (status IN ('pending', 'approved', 'consumed', 'denied', 'expired')),
  CONSTRAINT chk_hermes_device_code_platform
    CHECK (platform IN ('windows', 'darwin', 'linux')),
  CONSTRAINT chk_hermes_device_code_arch
    CHECK (arch IN ('amd64', 'arm64'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_device_codes_device_hash
  ON hermes_device_codes (device_code_hash);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_device_codes_user_hash
  ON hermes_device_codes (user_code_hash);
CREATE INDEX IF NOT EXISTS idx_hermes_device_codes_expires
  ON hermes_device_codes (expires_at);

CREATE TABLE IF NOT EXISTS hermes_devices (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  device_id varchar(36) NOT NULL,
  user_id bigint NOT NULL,
  public_key varchar(128) NOT NULL,
  key_fingerprint char(64) NOT NULL,
  device_name varchar(80) NOT NULL DEFAULT '',
  platform varchar(16) NOT NULL,
  arch varchar(16) NOT NULL,
  manager_version varchar(40) NOT NULL DEFAULT '',
  hermes_version varchar(40) NOT NULL DEFAULT '',
  actual_state varchar(24) NOT NULL DEFAULT 'registered',
  health_status varchar(24) NOT NULL DEFAULT 'unknown',
  applied_policy_revision bigint NOT NULL DEFAULT 0,
  config_digest char(64) NOT NULL DEFAULT '',
  last_error_code varchar(64) NOT NULL DEFAULT '',
  last_seen_at timestamptz(3) DEFAULT NULL,
  revoked_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_device_state CHECK (
    actual_state IN ('registered', 'installing', 'active', 'stopped', 'updating', 'revoked', 'error')
  ),
  CONSTRAINT chk_hermes_device_health CHECK (
    health_status IN ('unknown', 'healthy', 'degraded', 'unhealthy', 'policy_drift')
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_devices_device_id
  ON hermes_devices (device_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_devices_key_fingerprint
  ON hermes_devices (key_fingerprint);
CREATE INDEX IF NOT EXISTS idx_hermes_devices_tenant_user
  ON hermes_devices (tenant_id, user_id);
CREATE INDEX IF NOT EXISTS idx_hermes_devices_tenant_seen
  ON hermes_devices (tenant_id, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS hermes_policies (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  revision bigint NOT NULL,
  name varchar(80) NOT NULL,
  desired_state varchar(16) NOT NULL DEFAULT 'active',
  profile varchar(32) NOT NULL DEFAULT 'company',
  assistant_template_id varchar(64) NOT NULL DEFAULT '',
  assistant_template_revision bigint NOT NULL DEFAULT 0,
  artifact_id bigint NOT NULL DEFAULT 0,
  model_id bigint NOT NULL DEFAULT 0,
  model_name varchar(100) NOT NULL DEFAULT '',
  model_base_url varchar(255) NOT NULL DEFAULT '',
  toolsets jsonb NOT NULL DEFAULT '["clarify","memory","todo","no_mcp"]',
  privacy jsonb NOT NULL DEFAULT '{"upload_conversations":false,"upload_memory":false,"upload_local_files":false}',
  lease_seconds integer NOT NULL DEFAULT 3600,
  signature text NOT NULL DEFAULT '',
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_policy_state CHECK (desired_state IN ('active', 'stopped', 'revoked')),
  CONSTRAINT chk_hermes_policy_profile CHECK (profile = 'company'),
  CONSTRAINT chk_hermes_policy_lease CHECK (lease_seconds BETWEEN 300 AND 86400)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_policies_tenant_revision
  ON hermes_policies (tenant_id, revision);
CREATE INDEX IF NOT EXISTS idx_hermes_policies_tenant_created
  ON hermes_policies (tenant_id, created_at DESC);

CREATE TABLE IF NOT EXISTS hermes_artifacts (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  kind varchar(16) NOT NULL,
  platform varchar(16) NOT NULL,
  arch varchar(16) NOT NULL,
  version varchar(40) NOT NULL,
  upstream_commit varchar(64) NOT NULL DEFAULT '',
  source_url varchar(1024) NOT NULL,
  sha256 char(64) NOT NULL,
  signature text NOT NULL DEFAULT '',
  status varchar(16) NOT NULL DEFAULT 'pending',
  approved_by bigint NOT NULL DEFAULT 0,
  approved_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_artifact_kind CHECK (kind IN ('manager', 'hermes')),
  CONSTRAINT chk_hermes_artifact_platform CHECK (platform IN ('windows', 'darwin', 'linux', 'any')),
  CONSTRAINT chk_hermes_artifact_arch CHECK (arch IN ('amd64', 'arm64', 'any')),
  CONSTRAINT chk_hermes_artifact_status CHECK (status IN ('pending', 'approved', 'rejected', 'revoked'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_artifacts_release
  ON hermes_artifacts (tenant_id, kind, platform, arch, version);
CREATE INDEX IF NOT EXISTS idx_hermes_artifacts_downloads
  ON hermes_artifacts (tenant_id, kind, status, platform, arch);

CREATE TABLE IF NOT EXISTS hermes_device_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  device_id varchar(36) NOT NULL,
  event_type varchar(40) NOT NULL,
  result varchar(16) NOT NULL,
  error_code varchar(64) NOT NULL DEFAULT '',
  desired_policy_revision bigint NOT NULL DEFAULT 0,
  applied_policy_revision bigint NOT NULL DEFAULT 0,
  occurred_at timestamptz(3) NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_event_type CHECK (
    event_type IN ('registered', 'install', 'start', 'stop', 'update', 'rollback', 'apply_policy', 'policy_drift', 'revoke')
  ),
  CONSTRAINT chk_hermes_event_result CHECK (result IN ('started', 'succeeded', 'failed'))
);
CREATE INDEX IF NOT EXISTS idx_hermes_device_events_device_time
  ON hermes_device_events (tenant_id, device_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_hermes_device_events_tenant_time
  ON hermes_device_events (tenant_id, occurred_at DESC);

