-- Hermes M2：技能市场。技能 = 目录 + 必带 SKILL.md 的知识文档包（tarball）。
--
-- 控制面把 tarball 存 hermes_skills.content（bytea），经设备签名下载端点下发；
-- manager 校验 sha256 后直解压进 <profile>/skills/<name>/，员工 Hermes 自动发现
-- 即可用（上游 filesystem scan，无需 config 引用）。

CREATE TABLE IF NOT EXISTS hermes_skills (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  -- 成为 profile skills 目录名，必须文件系统安全（小写字母数字 + . _ -）
  name varchar(80) NOT NULL,
  display_name varchar(120) NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  -- 不可变版本号（同 hermes_artifacts.version 语义）
  version varchar(40) NOT NULL,
  -- tarball 摘要，manager 下载后强制校验
  sha256 char(64) NOT NULL,
  signature text NOT NULL DEFAULT '',
  -- tarball 本体（P0 由控制面自持下发）
  content bytea NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'pending',
  approved_by bigint NOT NULL DEFAULT 0,
  approved_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_skill_name CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,79}$'),
  CONSTRAINT chk_hermes_skill_status CHECK (status IN ('pending', 'approved', 'rejected', 'revoked'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_skills_tenant_name_version
  ON hermes_skills (tenant_id, name, version);
CREATE INDEX IF NOT EXISTS idx_hermes_skills_tenant_status
  ON hermes_skills (tenant_id, status);

-- 集群绑定：cluster 绑定某个技能版本（skill_id），随 desired-state 流到该集群全部 profile。
CREATE TABLE IF NOT EXISTS hermes_cluster_skills (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  cluster_id bigint NOT NULL,
  skill_id bigint NOT NULL,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_cluster_skill_refs CHECK (cluster_id > 0 AND skill_id > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_cluster_skills_cluster_skill
  ON hermes_cluster_skills (tenant_id, cluster_id, skill_id);
CREATE INDEX IF NOT EXISTS idx_hermes_cluster_skills_cluster
  ON hermes_cluster_skills (tenant_id, cluster_id);

