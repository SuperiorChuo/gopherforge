-- 1. company_cluster 策略 profile：为 dispatcher 开放白名单，仍是受控枚举。
ALTER TABLE hermes_policies DROP CONSTRAINT IF EXISTS chk_hermes_policy_profile;
ALTER TABLE hermes_policies ADD CONSTRAINT chk_hermes_policy_profile
  CHECK (profile IN ('company', 'company_cluster'));

-- 2. 集群层 hermes_clusters（company_cluster 分组）。
--    policy_id 0 = 未绑定 dispatcher 策略；绑定后必须是 profile='company_cluster' 的策略。
CREATE TABLE IF NOT EXISTS hermes_clusters (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  name varchar(80) NOT NULL,
  description text NOT NULL DEFAULT '',
  policy_id bigint NOT NULL DEFAULT 0,
  enabled boolean NOT NULL DEFAULT true,
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_cluster_name CHECK (length(name) BETWEEN 1 AND 80)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_clusters_tenant_name
  ON hermes_clusters (tenant_id, name);
CREATE INDEX IF NOT EXISTS idx_hermes_clusters_tenant_enabled
  ON hermes_clusters (tenant_id, enabled);

-- 3. 实例归属集群：cluster_id=0 表示未归组（一节点多实例方向不变，不建连接表）。
ALTER TABLE hermes_instances
  ADD COLUMN IF NOT EXISTS cluster_id bigint NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_hermes_instances_tenant_cluster
  ON hermes_instances (tenant_id, cluster_id);

-- 4. 任务定义 hermes_tasks：正文明文，状态 pending/active/completed/cancelled。
CREATE TABLE IF NOT EXISTS hermes_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  name varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  status varchar(16) NOT NULL DEFAULT 'pending',
  cluster_id bigint NOT NULL DEFAULT 0,
  -- 0 = 沿用集群策略（策略必须 profile='company_cluster'，否则 activate 拒绝）
  policy_id bigint NOT NULL DEFAULT 0,
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  started_at timestamptz(3) DEFAULT NULL,
  finished_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_task_status
    CHECK (status IN ('pending', 'active', 'completed', 'cancelled'))
);
CREATE INDEX IF NOT EXISTS idx_hermes_tasks_tenant_status
  ON hermes_tasks (tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_hermes_tasks_tenant_cluster
  ON hermes_tasks (tenant_id, cluster_id);

-- 5. 单实例执行记录 hermes_task_runs：assigned/running/completed/failed。
--    uk 阻止同一 (task, instance) 重复指派；取消任务时非终态 run 置 failed。
CREATE TABLE IF NOT EXISTS hermes_task_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  task_id bigint NOT NULL,
  instance_id bigint NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'assigned',
  result text NOT NULL DEFAULT '',
  started_at timestamptz(3) DEFAULT NULL,
  finished_at timestamptz(3) DEFAULT NULL,
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_task_run_status
    CHECK (status IN ('assigned', 'running', 'completed', 'failed'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_task_runs_task_instance
  ON hermes_task_runs (task_id, instance_id);
CREATE INDEX IF NOT EXISTS idx_hermes_task_runs_tenant_task
  ON hermes_task_runs (tenant_id, task_id);
CREATE INDEX IF NOT EXISTS idx_hermes_task_runs_tenant_instance
  ON hermes_task_runs (tenant_id, instance_id);

