-- Hermes Agent 实例层。
--
-- 缺口：策略此前绑在**用户**上（hermes_entitlements 一人一条，DesiredState 走
-- entitlement.policy_id），所以同一个人的所有设备只能跑同一套模型与工具集，
-- 系统里没有「一个有角色的 Agent」这个概念。
--
-- 本表把链路从「设备 → 权益(用户) → 策略」改成「设备(运行节点) → 实例(逻辑
-- Agent) → 策略」。设备是承载层（员工电脑 + manager），实例是逻辑体（角色、
-- 负责人、模型策略），两者生命周期独立：实例可以换负责人不换机器，也可以先
-- 建好不绑节点。
--
-- device_id **刻意不加唯一约束**：一个节点跑多个实例是既定方向。当前
-- gak-hermes-manager 硬编码了单实例（LaunchAgent 标签 com.gak.hermes、schtasks
-- 任务名 GakHermes、单个 HERMES_HOME 均为常量），故由服务层暂时拦截「同一节点
-- 第二个启用实例」；manager 支持多 profile 后去掉拦截即可，不需要改表。
CREATE TABLE IF NOT EXISTS hermes_instances (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  name varchar(80) NOT NULL,
  role varchar(40) NOT NULL DEFAULT 'default',
  owner_user_id bigint NOT NULL DEFAULT 0,
  -- 绑定的运行节点；空串表示实例已建但尚未放置到任何节点
  device_id varchar(36) NOT NULL DEFAULT '',
  -- 0 表示不覆盖，回落到权益策略 / 最新策略（保证存量设备行为不变）
  policy_id bigint NOT NULL DEFAULT 0,
  enabled boolean NOT NULL DEFAULT true,
  status varchar(16) NOT NULL DEFAULT 'unassigned',
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_instance_status
    CHECK (status IN ('unassigned', 'pending', 'running', 'error'))
);

-- 实例名在租户内唯一：它是管理员在任务派发时指认 Agent 的凭据，重名会歧义。
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_instances_tenant_name
  ON hermes_instances (tenant_id, name);
CREATE INDEX IF NOT EXISTS idx_hermes_instances_tenant_device
  ON hermes_instances (tenant_id, device_id);
CREATE INDEX IF NOT EXISTS idx_hermes_instances_tenant_owner
  ON hermes_instances (tenant_id, owner_user_id);

-- 存量设备各建一条实例：①「实例管理」页上线即有内容，不是空表
-- ②policy_id=0 走原回落链，现有设备的期望状态一字不变。
-- 名称冲突时跳过（ON CONFLICT），避免与管理员手工建的同名实例撞唯一索引。
INSERT INTO hermes_instances (tenant_id, name, role, owner_user_id, device_id, policy_id, enabled, status, created_at, updated_at)
SELECT
  d.tenant_id,
  COALESCE(NULLIF(d.device_name, ''), d.device_id),
  'default',
  d.user_id,
  d.device_id,
  0,
  true,
  CASE WHEN d.actual_state = 'active' THEN 'running' ELSE 'pending' END,
  NOW(),
  NOW()
FROM hermes_devices d
WHERE d.revoked_at IS NULL
ON CONFLICT DO NOTHING;

-- 实例管理权限。沿用 000033 的 ON CONFLICT DO NOTHING 写法。
INSERT INTO permissions (name, code, type, path, method, parent_id, created_at, updated_at) VALUES
('Hermes 实例查看', 'ai:hermes:instance:list', 2, '/api/v1/ai/hermes/instances', 'GET', 0, NOW(), NOW()),
('Hermes 实例管理', 'ai:hermes:instance:write', 2, '/api/v1/ai/hermes/instances', 'POST', 0, NOW(), NOW())
ON CONFLICT DO NOTHING;

-- 菜单：/hermes/instances 此前错指员工权益页，本期起它名副其实地管实例，
-- 标题「实例管理」保持不变；员工权益需要自己的入口，补一条挂到「资源中心」。
INSERT INTO menus (name, title, icon, path, component, parent_id, sort, status, hidden, permission, created_at, updated_at)
SELECT 'hermes-entitlements', '员工权益', 'team', '/hermes/entitlements', 'hermes/entitlements/index',
       (SELECT id FROM menus WHERE path = '/hermes/resources' LIMIT 1),
       5, 1, 0, 'ai:hermes:entitlement', NOW(), NOW()
WHERE EXISTS (SELECT 1 FROM menus WHERE path = '/hermes/resources')
  AND NOT EXISTS (SELECT 1 FROM menus WHERE path = '/hermes/entitlements');

UPDATE menus SET permission = 'ai:hermes:instance:list', updated_at = NOW()
WHERE path = '/hermes/instances';

