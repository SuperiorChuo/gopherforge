-- +goose Up
-- AI 平台化 Phase 1：模型配置数据库化 + 调用计量/审计 + 配额限流。
-- ai_models 存多供应商配置（api_key 密文 + iv 分列，只落库不进代码）；
-- ai_usage_logs 记每次调用的 token/费用/耗时/状态（异步写，不阻塞主流程）；
-- ai_quotas 三级配额（user > tenant > global），(scope, scope_id) 唯一。
-- 权限与菜单种子由主会话统一接线，此迁移只建表。

CREATE TABLE IF NOT EXISTS ai_models (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(100) NOT NULL,
  display_name varchar(100) NOT NULL,
  provider varchar(50) NOT NULL,
  api_key text NOT NULL DEFAULT '',
  api_key_iv varchar(32) NOT NULL DEFAULT '',
  base_url varchar(255) NOT NULL DEFAULT '',
  model_config json DEFAULT NULL,
  capabilities json DEFAULT NULL,
  status smallint NOT NULL DEFAULT 1,
  cost_per_1k_input decimal(10,6) NOT NULL DEFAULT 0,
  cost_per_1k_output decimal(10,6) NOT NULL DEFAULT 0,
  cost_per_image decimal(10,4) NOT NULL DEFAULT 0,
  daily_limit bigint DEFAULT NULL,
  description text NOT NULL DEFAULT '',
  sort bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) DEFAULT NULL,
  updated_at timestamptz(3) DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_models_name ON ai_models (name);
CREATE INDEX IF NOT EXISTS idx_ai_models_provider_status ON ai_models (provider, status);
CREATE INDEX IF NOT EXISTS idx_ai_models_sort ON ai_models (sort);

CREATE TABLE IF NOT EXISTS ai_usage_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  model_id bigint NOT NULL DEFAULT 0,
  model_name varchar(100) NOT NULL DEFAULT '',
  user_id bigint DEFAULT NULL,
  username varchar(100) NOT NULL DEFAULT '',
  tenant_id bigint DEFAULT NULL,
  operation varchar(50) NOT NULL DEFAULT '',
  prompt_tokens bigint DEFAULT NULL,
  completion_tokens bigint DEFAULT NULL,
  total_tokens bigint DEFAULT NULL,
  image_count bigint NOT NULL DEFAULT 0,
  cost decimal(10,4) NOT NULL DEFAULT 0,
  latency_ms bigint DEFAULT NULL,
  status varchar(20) NOT NULL DEFAULT '',
  error_msg text NOT NULL DEFAULT '',
  request_id varchar(100) NOT NULL DEFAULT '',
  ip varchar(50) NOT NULL DEFAULT '',
  user_agent varchar(255) NOT NULL DEFAULT '',
  created_at timestamptz(3) DEFAULT NULL,
  PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_ai_usage_model_time ON ai_usage_logs (model_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ai_usage_user_time ON ai_usage_logs (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ai_usage_tenant_time ON ai_usage_logs (tenant_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ai_usage_status ON ai_usage_logs (status);
CREATE INDEX IF NOT EXISTS idx_ai_usage_request_id ON ai_usage_logs (request_id);

CREATE TABLE IF NOT EXISTS ai_quotas (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  scope varchar(20) NOT NULL,
  scope_id bigint DEFAULT NULL,
  daily_token_limit bigint DEFAULT NULL,
  daily_cost_limit decimal(10,2) DEFAULT NULL,
  daily_request_limit bigint DEFAULT NULL,
  monthly_token_limit bigint DEFAULT NULL,
  monthly_cost_limit decimal(10,2) DEFAULT NULL,
  monthly_request_limit bigint DEFAULT NULL,
  reset_day_of_month bigint NOT NULL DEFAULT 1,
  enabled smallint NOT NULL DEFAULT 1,
  created_at timestamptz(3) DEFAULT NULL,
  updated_at timestamptz(3) DEFAULT NULL,
  PRIMARY KEY (id)
);

-- (scope, scope_id) 唯一：global 的 scope_id 为 NULL，PG 允许多个 NULL，
-- 故用 COALESCE 表达式索引把 global 归一到 0，保证全局配额也唯一。
CREATE UNIQUE INDEX IF NOT EXISTS uk_ai_quotas_scope ON ai_quotas (scope, COALESCE(scope_id, 0));
CREATE INDEX IF NOT EXISTS idx_ai_quotas_scope_enabled ON ai_quotas (scope, enabled);

