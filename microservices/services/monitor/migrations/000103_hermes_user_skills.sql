-- 无新权限、无菜单：自助端点在 JWT-only 自助块，员工工作台本就无门槛。
CREATE TABLE IF NOT EXISTS hermes_user_skills (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  user_id bigint NOT NULL,
  skill_id bigint NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_user_skills_ids CHECK (user_id > 0 AND skill_id > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_user_skills_tenant_user_skill
  ON hermes_user_skills (tenant_id, user_id, skill_id);
CREATE INDEX IF NOT EXISTS idx_hermes_user_skills_user
  ON hermes_user_skills (user_id);

