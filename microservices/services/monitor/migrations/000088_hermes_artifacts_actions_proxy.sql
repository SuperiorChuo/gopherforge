INSERT INTO permissions (name, code, type, path, method, parent_id, created_at, updated_at) VALUES
('Hermes 制品录入', 'ai:hermes:artifact:write', 2, '/api/v1/ai/hermes/artifacts', 'POST', 0, NOW(), NOW()),
('Hermes 设备运维动作', 'ai:hermes:device:action', 2, '/api/v1/ai/hermes/devices/:device_id/actions', 'POST', 0, NOW(), NOW())
ON CONFLICT DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.code = 'super_admin'
  AND p.code IN ('ai:hermes:artifact:write', 'ai:hermes:device:action')
  AND NOT EXISTS (
    SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id
  );

