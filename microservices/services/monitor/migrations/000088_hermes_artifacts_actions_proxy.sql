-- CHECK 限死取值，而不是自由文本列。

-- ---------------------------------------------------------------------------
-- 1. 设备运维动作：管理员置位，manager 拉取期望状态时读到，执行完经事件回执清除
-- ---------------------------------------------------------------------------
ALTER TABLE hermes_devices
  ADD COLUMN IF NOT EXISTS pending_action varchar(24) NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS pending_action_at timestamptz(3) DEFAULT NULL;

-- 约束用 DROP + ADD 表达幂等，而不是 DO $$ ... $$ 块：goose 按分号切分语句，
-- dollar-quoted 块会被从中间截断（psql 能跑、goose 报 unterminated dollar-quoted
-- string）。本仓此前没有 DO 块先例，这里避开它。
ALTER TABLE hermes_devices DROP CONSTRAINT IF EXISTS chk_hermes_device_pending_action;
ALTER TABLE hermes_devices ADD CONSTRAINT chk_hermes_device_pending_action
  CHECK (pending_action IN ('', 'retry_update', 'apply_policy', 'restart'));

-- ---------------------------------------------------------------------------
-- 2. 模型代理用量归属到设备
--    正文不落库，这里只加归属列，供按 tenant/user/device 做额度与审计。
-- ---------------------------------------------------------------------------
ALTER TABLE ai_usage_logs
  ADD COLUMN IF NOT EXISTS device_id varchar(36) NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_ai_usage_logs_device_time
  ON ai_usage_logs (device_id, created_at DESC) WHERE device_id <> '';

-- ---------------------------------------------------------------------------
-- 3. 短期模型访问 token
--    Hermes 是原生上游，只会发标准 OpenAI 请求 + Bearer token，不会用设备的
--    逐请求 Ed25519 签名协议。因此代理需要独立的 bearer 凭据：manager 用它
--    已有的签名身份换取短期 token，再写进受管 profile 给 Hermes 用。
--    只存哈希（与 hermes_device_codes 同惯例），明文仅在签发时返回一次。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS hermes_model_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  token_hash char(64) NOT NULL,
  device_id varchar(36) NOT NULL,
  user_id bigint NOT NULL,
  expires_at timestamptz(3) NOT NULL,
  revoked_at timestamptz(3) DEFAULT NULL,
  last_used_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_model_tokens_hash
  ON hermes_model_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_hermes_model_tokens_device
  ON hermes_model_tokens (tenant_id, device_id, expires_at DESC);

