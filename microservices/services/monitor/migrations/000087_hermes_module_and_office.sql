-- ---------------------------------------------------------------------------
-- 5. 办公室地图数据表
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS hermes_office_floors (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  name varchar(80) NOT NULL,
  sort int NOT NULL DEFAULT 0,
  -- 平面尺寸（米）：3D 里 width→X 轴，depth→Z 轴
  width numeric(8,2) NOT NULL DEFAULT 20,
  depth numeric(8,2) NOT NULL DEFAULT 15,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_office_floor_size CHECK (width > 0 AND depth > 0)
);
CREATE INDEX IF NOT EXISTS idx_hermes_office_floors_tenant
  ON hermes_office_floors (tenant_id, sort, id);

CREATE TABLE IF NOT EXISTS hermes_office_seats (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  floor_id bigint NOT NULL,
  label varchar(40) NOT NULL DEFAULT '',
  x numeric(8,2) NOT NULL DEFAULT 0,
  -- 平面第二轴，3D 里映射到 z
  y numeric(8,2) NOT NULL DEFAULT 0,
  -- 朝向（度）
  rotation numeric(6,2) NOT NULL DEFAULT 0,
  -- 0 = 空位
  user_id bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_office_seat_rotation CHECK (rotation >= 0 AND rotation < 360)
);
CREATE INDEX IF NOT EXISTS idx_hermes_office_seats_floor
  ON hermes_office_seats (tenant_id, floor_id);
-- 一人一工位：仅对已绑定员工的行生效，空位（user_id=0）不受约束
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_office_seats_user
  ON hermes_office_seats (tenant_id, user_id) WHERE user_id > 0;

