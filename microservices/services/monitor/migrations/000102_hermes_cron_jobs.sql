-- 1. 定时任务定义 hermes_cron_jobs
CREATE TABLE IF NOT EXISTS hermes_cron_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  name varchar(80) NOT NULL,
  description text NOT NULL DEFAULT '',
  cron_expression varchar(40) NOT NULL,
  -- 动作类型：v1 仅 prompt（推提示词给本地 Hermes）；未来扩展 skill 等
  action_type varchar(16) NOT NULL DEFAULT 'prompt',
  prompt text NOT NULL DEFAULT '',
  enabled boolean NOT NULL DEFAULT true,
  created_by bigint NOT NULL DEFAULT 0,
  updated_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_cron_job_name
    CHECK (length(name) BETWEEN 1 AND 80),
  CONSTRAINT chk_hermes_cron_job_action
    CHECK (action_type IN ('prompt'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_cron_jobs_tenant_name
  ON hermes_cron_jobs (tenant_id, name);
CREATE INDEX IF NOT EXISTS idx_hermes_cron_jobs_tenant_enabled
  ON hermes_cron_jobs (tenant_id, enabled);

-- 2. 触发审计 hermes_cron_runs：每次设备端执行记录一条。设备写，控制面只读列表。
CREATE TABLE IF NOT EXISTS hermes_cron_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  job_id bigint NOT NULL,
  device_id varchar(64) NOT NULL DEFAULT '',
  status varchar(16) NOT NULL DEFAULT 'triggered',
  result text NOT NULL DEFAULT '',
  triggered_at timestamptz(3) DEFAULT NULL,
  finished_at timestamptz(3) DEFAULT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_cron_run_status
    CHECK (status IN ('triggered', 'completed', 'failed'))
);
CREATE INDEX IF NOT EXISTS idx_hermes_cron_runs_tenant_job
  ON hermes_cron_runs (tenant_id, job_id, created_at);
CREATE INDEX IF NOT EXISTS idx_hermes_cron_runs_tenant_device
  ON hermes_cron_runs (tenant_id, device_id);

-- 3. 权限：ai:hermes:cron:list / write，仅默认授予 super_admin。
INSERT INTO permissions (name, code, type, path, method, parent_id, created_at, updated_at) VALUES
('Hermes 定时任务查看', 'ai:hermes:cron:list', 2, '/api/v1/ai/hermes/cron', 'GET', 0, NOW(), NOW()),
('Hermes 定时任务管理', 'ai:hermes:cron:write', 2, '/api/v1/ai/hermes/cron', 'POST', 0, NOW(), NOW())
ON CONFLICT DO NOTHING;

INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM roles r
CROSS JOIN permissions p
WHERE r.code = 'super_admin'
  AND p.code IN ('ai:hermes:cron:list', 'ai:hermes:cron:write')
  AND NOT EXISTS (
    SELECT 1 FROM role_permissions rp WHERE rp.role_id = r.id AND rp.permission_id = p.id
  );

-- 4. 菜单：定时任务挂「协同运维」（/hermes/collaboration 容器）。新路径 /hermes/cron 不与现有页面冲突。
INSERT INTO menus (name, title, icon, path, component, parent_id, sort, status, hidden, permission, created_at, updated_at)
SELECT 'hermes-cron', '定时任务', 'schedule', '/hermes/cron', 'hermes/cron/index',
       (SELECT id FROM menus WHERE path = '/hermes/collaboration' LIMIT 1),
       6, 1, 0, 'ai:hermes:cron:list', NOW(), NOW()
WHERE EXISTS (SELECT 1 FROM menus WHERE path = '/hermes/collaboration')
  AND NOT EXISTS (SELECT 1 FROM menus WHERE path = '/hermes/cron');

INSERT INTO menu_permissions (menu_id, permission_id)
SELECT m.id, p.id
FROM menus m
JOIN permissions p ON p.code = m.permission
WHERE m.path = '/hermes/cron'
ON CONFLICT DO NOTHING;

