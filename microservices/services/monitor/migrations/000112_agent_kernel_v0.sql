CREATE TABLE IF NOT EXISTS ai_svc.agent_definitions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  agent_key varchar(64) NOT NULL,
  name varchar(100) NOT NULL,
  description varchar(500) NOT NULL DEFAULT '',
  status varchar(16) NOT NULL DEFAULT 'active',
  latest_version_id bigint,
  created_by bigint NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  deleted_at timestamptz(3),
  CONSTRAINT ck_agent_definitions_status CHECK (status IN ('active', 'disabled')),
  CONSTRAINT ck_agent_definitions_key CHECK (agent_key ~ '^[a-z][a-z0-9_-]{1,63}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_definitions_tenant_key
  ON ai_svc.agent_definitions (tenant_id, agent_key) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_agent_definitions_tenant_status
  ON ai_svc.agent_definitions (tenant_id, status, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS ai_svc.agent_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  agent_definition_id bigint NOT NULL REFERENCES ai_svc.agent_definitions (id) ON DELETE RESTRICT,
  version integer NOT NULL,
  schema_version varchar(32) NOT NULL DEFAULT 'agent-spec/v1',
  model_id bigint NOT NULL REFERENCES ai_svc.ai_models (id) ON DELETE RESTRICT,
  instructions text NOT NULL,
  tools jsonb NOT NULL DEFAULT '[]'::jsonb,
  max_steps integer NOT NULL DEFAULT 8,
  timeout_seconds integer NOT NULL DEFAULT 120,
  spec jsonb NOT NULL,
  spec_sha256 char(64) NOT NULL,
  created_by bigint NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_agent_versions_definition_version UNIQUE (agent_definition_id, version),
  CONSTRAINT ck_agent_versions_schema CHECK (schema_version = 'agent-spec/v1'),
  CONSTRAINT ck_agent_versions_tools CHECK (jsonb_typeof(tools) = 'array'),
  CONSTRAINT ck_agent_versions_steps CHECK (max_steps BETWEEN 1 AND 32),
  CONSTRAINT ck_agent_versions_timeout CHECK (timeout_seconds BETWEEN 10 AND 600),
  CONSTRAINT ck_agent_versions_instructions CHECK (char_length(instructions) BETWEEN 1 AND 20000)
);
CREATE INDEX IF NOT EXISTS idx_agent_versions_tenant_definition
  ON ai_svc.agent_versions (tenant_id, agent_definition_id, version DESC);

ALTER TABLE ai_svc.agent_definitions
  ADD CONSTRAINT fk_agent_definitions_latest_version
  FOREIGN KEY (latest_version_id) REFERENCES ai_svc.agent_versions (id) ON DELETE SET NULL;

-- 版本工具授权是不可变 Spec 的关系化投影；工具实现与 Schema 仍由服务端代码登记。
CREATE TABLE IF NOT EXISTS ai_svc.agent_version_tools (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  agent_version_id bigint NOT NULL REFERENCES ai_svc.agent_versions (id) ON DELETE CASCADE,
  tool_name varchar(64) NOT NULL,
  tool_spec_sha256 char(64) NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_agent_version_tools UNIQUE (agent_version_id, tool_name),
  CONSTRAINT ck_agent_version_tools_name CHECK (tool_name ~ '^[a-z][a-z0-9_]{1,63}$')
);
CREATE INDEX IF NOT EXISTS idx_agent_version_tools_tenant
  ON ai_svc.agent_version_tools (tenant_id, agent_version_id);

CREATE TABLE IF NOT EXISTS ai_svc.agent_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  agent_definition_id bigint NOT NULL REFERENCES ai_svc.agent_definitions (id) ON DELETE RESTRICT,
  agent_version_id bigint NOT NULL REFERENCES ai_svc.agent_versions (id) ON DELETE RESTRICT,
  requested_by bigint NOT NULL,
  idempotency_key varchar(128) NOT NULL,
  request_sha256 char(64) NOT NULL,
  input text NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'queued',
  attempt integer NOT NULL DEFAULT 0,
  max_steps integer NOT NULL,
  timeout_seconds integer NOT NULL,
  checkpoint jsonb NOT NULL DEFAULT '{"schema":"agent-checkpoint/v1","next_ordinal":1,"messages":[]}'::jsonb,
  output text NOT NULL DEFAULT '',
  error_code varchar(64) NOT NULL DEFAULT '',
  error_message varchar(500) NOT NULL DEFAULT '',
  lease_owner varchar(128) NOT NULL DEFAULT '',
  lease_expires_at timestamptz(3),
  heartbeat_at timestamptz(3),
  cancel_requested_at timestamptz(3),
  started_at timestamptz(3),
  finished_at timestamptz(3),
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_agent_runs_idempotency UNIQUE (tenant_id, requested_by, idempotency_key),
  CONSTRAINT ck_agent_runs_status CHECK (status IN ('queued', 'running', 'cancelling', 'succeeded', 'failed', 'cancelled')),
  CONSTRAINT ck_agent_runs_attempt CHECK (attempt >= 0),
  CONSTRAINT ck_agent_runs_steps CHECK (max_steps BETWEEN 1 AND 32),
  CONSTRAINT ck_agent_runs_timeout CHECK (timeout_seconds BETWEEN 10 AND 600),
  CONSTRAINT ck_agent_runs_input CHECK (char_length(input) BETWEEN 1 AND 20000)
);
CREATE INDEX IF NOT EXISTS idx_agent_runs_tenant_created
  ON ai_svc.agent_runs (tenant_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_agent_runs_tenant_agent
  ON ai_svc.agent_runs (tenant_id, agent_definition_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_agent_runs_claim
  ON ai_svc.agent_runs (status, lease_expires_at, id)
  WHERE status IN ('queued', 'running', 'cancelling');

CREATE TABLE IF NOT EXISTS ai_svc.agent_steps (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  run_id bigint NOT NULL REFERENCES ai_svc.agent_runs (id) ON DELETE CASCADE,
  ordinal integer NOT NULL,
  kind varchar(16) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'running',
  name varchar(100) NOT NULL DEFAULT '',
  request jsonb NOT NULL DEFAULT '{}'::jsonb,
  response jsonb NOT NULL DEFAULT '{}'::jsonb,
  input_tokens integer NOT NULL DEFAULT 0,
  output_tokens integer NOT NULL DEFAULT 0,
  stop_reason varchar(64) NOT NULL DEFAULT '',
  error_code varchar(64) NOT NULL DEFAULT '',
  error_message varchar(500) NOT NULL DEFAULT '',
  started_at timestamptz(3) NOT NULL DEFAULT NOW(),
  finished_at timestamptz(3),
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_agent_steps_run_ordinal UNIQUE (run_id, ordinal),
  CONSTRAINT ck_agent_steps_ordinal CHECK (ordinal > 0),
  CONSTRAINT ck_agent_steps_kind CHECK (kind IN ('model', 'tool')),
  CONSTRAINT ck_agent_steps_status CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled')),
  CONSTRAINT ck_agent_steps_tokens CHECK (input_tokens >= 0 AND output_tokens >= 0)
);
CREATE INDEX IF NOT EXISTS idx_agent_steps_tenant_run
  ON ai_svc.agent_steps (tenant_id, run_id, ordinal);

CREATE TABLE IF NOT EXISTS ai_svc.agent_tool_calls (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  run_id bigint NOT NULL REFERENCES ai_svc.agent_runs (id) ON DELETE CASCADE,
  step_id bigint NOT NULL REFERENCES ai_svc.agent_steps (id) ON DELETE CASCADE,
  provider_call_id varchar(128) NOT NULL DEFAULT '',
  idempotency_key varchar(128) NOT NULL,
  tool_name varchar(64) NOT NULL,
  arguments jsonb NOT NULL,
  arguments_sha256 char(64) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'running',
  result jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_code varchar(64) NOT NULL DEFAULT '',
  error_message varchar(500) NOT NULL DEFAULT '',
  attempt integer NOT NULL DEFAULT 1,
  started_at timestamptz(3) NOT NULL DEFAULT NOW(),
  finished_at timestamptz(3),
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_agent_tool_calls_idempotency UNIQUE (tenant_id, idempotency_key),
  CONSTRAINT ck_agent_tool_calls_status CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled')),
  CONSTRAINT ck_agent_tool_calls_attempt CHECK (attempt > 0)
);
CREATE INDEX IF NOT EXISTS idx_agent_tool_calls_tenant_run
  ON ai_svc.agent_tool_calls (tenant_id, run_id, id);

CREATE TABLE IF NOT EXISTS ai_svc.agent_run_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id bigint NOT NULL,
  run_id bigint NOT NULL REFERENCES ai_svc.agent_runs (id) ON DELETE CASCADE,
  step_id bigint REFERENCES ai_svc.agent_steps (id) ON DELETE SET NULL,
  schema_version varchar(32) NOT NULL DEFAULT 'run-event/v1',
  event_type varchar(64) NOT NULL,
  data jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz(3) NOT NULL DEFAULT NOW(),
  CONSTRAINT ck_agent_run_events_schema CHECK (schema_version = 'run-event/v1')
);
CREATE INDEX IF NOT EXISTS idx_agent_run_events_tenant_run_cursor
  ON ai_svc.agent_run_events (tenant_id, run_id, id);

-- AgentVersion 只能新增，避免 Run 绑定的历史行为被静默改写。
-- +goose StatementBegin
CREATE OR REPLACE FUNCTION ai_svc.gak_reject_agent_version_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'agent versions are immutable';
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER trg_agent_versions_immutable
BEFORE UPDATE OR DELETE ON ai_svc.agent_versions
FOR EACH ROW EXECUTE FUNCTION ai_svc.gak_reject_agent_version_mutation();

