-- +goose Up
-- Hermes M3：MCP 管理。员工 Hermes 连接公司批准的内部系统（HTTP/SSE）与本地
-- 工具（stdio），控制面管 MCP server 白名单与配置，manager 受控注入。
--
-- secret_json 存明文密钥（同 M2 存 skill tarball 的一致取舍），只经设备签名
-- 端点 /device/mcp-secrets 读取；desired-state 只带 ${VAR} 模板 + secret_revision。
-- 密钥 at-rest 的 KMS/列加密是后续项。

CREATE TABLE IF NOT EXISTS hermes_mcp_servers (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  -- 成为上游 mcp_servers 配置键名，必须文件系统安全
  name varchar(80) NOT NULL,
  display_name varchar(120) NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  -- stdio = 本地命令；sse/http = 远程端点
  type varchar(8) NOT NULL,
  command varchar(32) NOT NULL DEFAULT '',
  args jsonb NOT NULL DEFAULT '[]',
  url varchar(1024) NOT NULL DEFAULT '',
  env jsonb NOT NULL DEFAULT '{}',
  headers jsonb NOT NULL DEFAULT '{}',
  tools_include jsonb NOT NULL DEFAULT '[]',
  tools_exclude jsonb NOT NULL DEFAULT '[]',
  timeout int NOT NULL DEFAULT 0,
  status varchar(16) NOT NULL DEFAULT 'pending',
  approved_by bigint NOT NULL DEFAULT 0,
  approved_at timestamptz(3) DEFAULT NULL,
  -- 密钥版本：secret_json 变更时自增，digest 含它以感知轮换
  secret_revision bigint NOT NULL DEFAULT 0,
  -- 明文密钥（jsonb），只经设备签名端点读取，list/创建响应均不返回
  secret_json jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  updated_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_mcp_server_name CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,79}$'),
  CONSTRAINT chk_hermes_mcp_server_type CHECK (type IN ('stdio', 'sse', 'http')),
  CONSTRAINT chk_hermes_mcp_server_status CHECK (status IN ('pending', 'approved', 'rejected', 'revoked'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_mcp_servers_tenant_name
  ON hermes_mcp_servers (tenant_id, name);
CREATE INDEX IF NOT EXISTS idx_hermes_mcp_servers_tenant_status
  ON hermes_mcp_servers (tenant_id, status);

-- 集群绑定：cluster 绑定某个已审批 MCP server，随 desired-state 流到该集群全部 profile。
CREATE TABLE IF NOT EXISTS hermes_cluster_mcp_servers (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tenant_id bigint NOT NULL DEFAULT 1,
  cluster_id bigint NOT NULL,
  server_id bigint NOT NULL,
  created_by bigint NOT NULL DEFAULT 0,
  created_at timestamptz(3) NOT NULL DEFAULT NOW(),
  PRIMARY KEY (id),
  CONSTRAINT chk_hermes_cluster_mcp_refs CHECK (cluster_id > 0 AND server_id > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_hermes_cluster_mcp_servers_cluster_server
  ON hermes_cluster_mcp_servers (tenant_id, cluster_id, server_id);
CREATE INDEX IF NOT EXISTS idx_hermes_cluster_mcp_servers_cluster
  ON hermes_cluster_mcp_servers (tenant_id, cluster_id);

